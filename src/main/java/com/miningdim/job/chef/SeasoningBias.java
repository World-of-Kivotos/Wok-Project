package com.miningdim.job.chef;

/**
 * 调料偏置方向 (Chef_Job_DesignSpec 第五章 调料->效果池映射)。投入的调料把效果掷点偏向某个池。
 *
 * NONE = 无调料或未识别 (掷点用品质档默认全池, 不偏置)。其余对应第五章表的七个方向。
 */
public enum SeasoningBias {

    /** 无偏置 (无调料/未识别): 用品质档默认全解锁池。 */
    NONE,
    /** 盐/酱油/椒盐: 续航鲜味 (耐饥/增量/增香)。 */
    SAVORY,
    /** 糖/糖浆: buff 强化 (增香/回味)。 */
    SWEET,
    /** 油/黄油/奶油: 战斗辅助 (披甲/膳香, 高品质门控)。 */
    OILY,
    /** 醋: 净化/解控 (回甘/稳膛)。 */
    SOUR,
    /** 辣椒/花椒: 战斗/急迫 (膳香/急速)。 */
    SPICY,
    /** 姜/蒜/孜然: 驱寒保健/探索 (夜照/耐饥)。 */
    AROMATIC,
    /** 咖喱/火锅底料: 高级复合 (多效果, 闪耀向 - 偏全池不收窄)。 */
    COMPLEX
}
